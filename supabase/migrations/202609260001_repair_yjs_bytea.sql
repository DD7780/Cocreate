begin;

create table if not exists public.project_persistence_quarantine (
  id bigint generated by default as identity primary key,
  project_id uuid not null references public.projects(id) on delete cascade,
  record_kind text not null check (record_kind in ('snapshot','update')),
  source_revision bigint not null,
  raw_bytes bytea not null,
  reason text not null,
  quarantined_at timestamptz not null default now(),
  unique(project_id,record_kind,source_revision)
);

alter table public.project_persistence_quarantine enable row level security;
revoke all on public.project_persistence_quarantine from anon, authenticated;

insert into public.project_persistence_quarantine(project_id,record_kind,source_revision,raw_bytes,reason)
select project_id,'snapshot',revision,yjs_state,'Backup before repairing legacy Node Buffer JSON serialization'
from public.project_snapshots
where starts_with(encode(yjs_state,'hex'),'7b2274797065223a22427566666572222c2264617461223a5b')
on conflict do nothing;

insert into public.project_persistence_quarantine(project_id,record_kind,source_revision,raw_bytes,reason)
select project_id,'update',sequence,update_bytes,'Backup before repairing legacy Node Buffer JSON serialization'
from public.project_document_updates
where starts_with(encode(update_bytes,'hex'),'7b2274797065223a22427566666572222c2264617461223a5b')
on conflict do nothing;

commit;
